#!/usr/bin/env node
// Waymark spike: .way source -> one self-contained HTML file.
//
//   node spike/viz.mjs examples/shop/place_order.way -o spike/out/shop.html
//   node spike/viz.mjs examples/shop/place_order.way --static --machine PlaceOrder -o spike/out/shop-PlaceOrder.static.html
//
// Default: the interactive viewer (elkjs, viewer JS/CSS and the IR all inlined; works from file://).
// --static: elkjs runs here in Node and the page is script-free: <style> + inline <svg> + legend.

import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { compile, formatDiagnostic } from './compile.mjs'
import { sourceText } from './viewer/model.js'
import { layoutMachine } from './viewer/layout.js'
import { renderSvg, renderLegend, renderMachineHeader, esc } from './viewer/render.js'

const here = path.dirname(fileURLToPath(import.meta.url))
const require = createRequire(import.meta.url)
const read = (...p) => fs.readFileSync(path.join(here, ...p), 'utf8')

function usage(msg) {
  if (msg) console.error(`viz: ${msg}`)
  console.error('usage: node viz.mjs <file.way> -o <out.html> [--static --machine <Name>]')
  process.exit(2)
}

const argv = process.argv.slice(2)
let input = null, out = null, isStatic = false, machineName = null
for (let i = 0; i < argv.length; i++) {
  const a = argv[i]
  if (a === '-o' || a === '--out') out = argv[++i]
  else if (a === '--static') isStatic = true
  else if (a === '--machine') machineName = argv[++i]
  else if (a.startsWith('-')) usage(`unknown option ${a}`)
  else if (input) usage('one input file, please')
  else input = a
}
if (!input || !out) usage()

const { ir, diagnostics, ok } = compile(input)
for (const d of diagnostics) console.error(formatDiagnostic(d))
if (!ok) process.exit(1)

const machines = Object.keys(ir.machines)
if (!machines.length) usage(`${input} declares no machines`)
if (machineName && !ir.machines[machineName]) usage(`no machine \`${machineName}\` in ${input} (found: ${machines.join(', ')})`)

// Inline <script> content must not contain "</script" or "<!--".
const inlineJs = (js) => js.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--')
const inlineJson = (v) => JSON.stringify(v).replace(/</g, '\\u003c')
const css = read('viewer', 'viewer.css')

let html
if (isStatic) {
  const name = machineName ?? machines[0]
  const ELK = require('elkjs/lib/elk.bundled.js')
  const layout = await layoutMachine(ir, name, new ELK())
  if (layout.fallback) console.error(`viz: ELK failed with the preferred options for ${name}; used fallback ${layout.fallback}`)
  const svg = renderSvg(ir, name, layout)
  html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(name)} · Waymark</title>
<style>
${css}</style>
</head>
<body class="wm-static">
<header>
<h1>${esc(name)}<small>${esc(sourceText(ir, ir.machines[name].span))}</small></h1>
${renderMachineHeader(ir, name)}
</header>
<figure>
${svg}
</figure>
<section>
<h2>Legend</h2>
${renderLegend({ interactive: false })}
</section>
<footer>Static rendering of machine <code>${esc(name)}</code> from <code>${esc(ir.sources[0].path)}</code>. No scripts; generated by the Waymark spike.</footer>
</body>
</html>
`
} else {
  // The viewer sources are ES modules so Node can import them. For the browser they are
  // concatenated into one classic script: drop the import lines and the `export` keyword.
  const js = ['model.js', 'layout.js', 'render.js', 'app.js']
    .map((f) => `// ── viewer/${f}\n` + read('viewer', f).replace(/^import .*$/gm, '').replace(/^export /gm, ''))
    .join('\n')
  const elk = fs.readFileSync(require.resolve('elkjs/lib/elk.bundled.js'), 'utf8')
  const parts = {
    TITLE: esc(`${path.basename(input)} · Waymark`),
    CSS: css,
    IR: inlineJson(ir),
    INITIAL: esc(machineName ?? ''),
    ELK: inlineJs(elk),
    JS: inlineJs(`(function () {\n'use strict'\n${js}\n})()`),
  }
  html = read('viewer', 'index.html').replace(/\/\*@(\w+)@\*\/|<!--@(\w+)@-->/g, (_, a, b) => parts[a ?? b] ?? '')
}

fs.mkdirSync(path.dirname(path.resolve(out)), { recursive: true })
fs.writeFileSync(out, html)
console.error(`viz: wrote ${out} (${(html.length / 1024).toFixed(0)} kB, ${isStatic ? 'static, ' + (machineName ?? machines[0]) : machines.length + ' machine' + (machines.length === 1 ? '' : 's')})`)
